    /**
     * Resolves the argument definition for an event class.
     *
     * Falls back to PHPStan reflection to map a project's own subclass of a known event class
     * onto its mapped ancestor. Reflection is never used to invent a definition.
     *
     * @param array<string, array{order: string[], getters: array<string, string>, resultAware: bool}> $map
     *
     * @return array{order: string[], getters: array<string, string>, resultAware: bool}|null
     */
    public function resolveDefinition(array $map, string $className): ?array
    {
        $className = ltrim($className, '\\');

        if (self::isGenericEventClass($className)) {
            return null;
        }

        if (isset($map[$className])) {
            return $map[$className];
        }

        if (!$this->reflectionProvider->hasClass($className)) {
            return null;
        }

        foreach ($this->reflectionProvider->getClass($className)->getParents() as $parentReflection) {
            $parentName = $parentReflection->getName();

            if (self::isGenericEventClass($parentName)) {
                return null;
            }

            if (isset($map[$parentName])) {
                return $map[$parentName];
            }
        }

        return null;
    }

