    /**
     * Merges a rule's configured event definitions over the generated defaults.
     *
     * @param mixed $configuration The raw value of the rule's event map option.
     *
     * @return array<string, array{order: string[], getters: array<string, string>, resultAware: bool}>
     */
    public static function mergeConfiguration($configuration): array
    {
        if (!\is_array($configuration)) {
            return self::DEFAULT_EVENT_ARGUMENT_MAP;
        }

        $normalised = [];

        foreach ($configuration as $className => $definition) {
            if (!\is_string($className) || !\is_array($definition)) {
                continue;
            }

            $normalisedDefinition = self::normaliseDefinition($definition);

            if ($normalisedDefinition !== null) {
                $normalised[ltrim($className, '\\')] = $normalisedDefinition;
            }
        }

        // Configured entries override the generated defaults.
        return $normalised + self::DEFAULT_EVENT_ARGUMENT_MAP;
    }

    /**
     * Accepts three notations for a configured event definition:
     *
     *   ['context', 'item']                                   positional, getters by convention
     *   ['context' => 'getContext', 'subject' => 'getItem']    argument name => getter
     *   ['order' => [...], 'getters' => [...]]                 both parts explicitly
     *
     * @param array<mixed> $definition
     *
     * @return array{order: string[], getters: array<string, string>, resultAware: bool}|null
     */
    public static function normaliseDefinition(array $definition): ?array
    {
        $resultAware = (bool) ($definition['resultAware'] ?? false);

        if (isset($definition['order']) || isset($definition['getters'])) {
            $order   = [];
            $getters = [];

            foreach ((array) ($definition['order'] ?? []) as $argumentName) {
                if (\is_string($argumentName)) {
                    $order[] = $argumentName;
                }
            }

            foreach ((array) ($definition['getters'] ?? []) as $argumentName => $getter) {
                if (\is_string($argumentName) && \is_string($getter)) {
                    $getters[$argumentName] = $getter;
                }
            }

            // Fill in getters for order entries that were not given explicitly.
            foreach ($order as $argumentName) {
                $getters[$argumentName] ??= 'get' . ucfirst($argumentName);
            }

            return $getters === [] ? null : ['order' => $order, 'getters' => $getters, 'resultAware' => $resultAware];
        }

        if (array_is_list($definition)) {
            $order   = [];
            $getters = [];

            foreach ($definition as $argumentName) {
                if (!\is_string($argumentName)) {
                    return null;
                }

                $order[]                = $argumentName;
                $getters[$argumentName] = 'get' . ucfirst($argumentName);
            }

            return $getters === [] ? null : ['order' => $order, 'getters' => $getters, 'resultAware' => $resultAware];
        }

        $getters = [];

        foreach ($definition as $argumentName => $getter) {
            if ($argumentName === 'resultAware') {
                continue;
            }

            if (!\is_string($argumentName) || !\is_string($getter)) {
                return null;
            }

            $getters[$argumentName] = $getter;
        }

        if ($getters === []) {
            return null;
        }

        return ['order' => array_keys($getters), 'getters' => $getters, 'resultAware' => $resultAware];
    }

    /**
     * Tells whether the class is one of the base event types that carry no concrete arguments.
