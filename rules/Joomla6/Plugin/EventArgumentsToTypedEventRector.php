    /**
     * Accepts three notations for a configured event definition:
     *
     *   ['context', 'item']                            positional, getters by convention
     *   ['context' => 'getContext', 'subject' => 'getItem']   argument name => getter
     *   ['order' => [...], 'getters' => [...]]         both parts explicitly
     *
     * @param array<mixed> $definition
     *
     * @return array{order: string[], getters: array<string, string>}|null
     */
    private function normaliseDefinition(array $definition): ?array
    {
        if (isset($definition['order']) || isset($definition['getters'])) {
            $order   = [];
            $getters = [];

            foreach ((array) ($definition['order'] ?? []) as $argumentName) {
                if (\is_string($argumentName)) {
                    $order[] = $argumentName;
                }
            }

            foreach ((array) ($definition['getters'] ?? []) as $argumentName => $getter) {
                if (\is_string($argumentName) && \is_string($getter)) {
                    $getters[$argumentName] = $getter;
                }
            }

            // Fill in getters for order entries that were not given explicitly.
            foreach ($order as $argumentName) {
                $getters[$argumentName] ??= 'get' . ucfirst($argumentName);
            }

            return $getters === [] ? null : ['order' => $order, 'getters' => $getters];
        }

        if (array_is_list($definition)) {
            $order   = [];
            $getters = [];

            foreach ($definition as $argumentName) {
                if (!\is_string($argumentName)) {
                    return null;
                }

                $order[]                = $argumentName;
                $getters[$argumentName] = 'get' . ucfirst($argumentName);
            }

            return $getters === [] ? null : ['order' => $order, 'getters' => $getters];
        }

        $getters = [];

        foreach ($definition as $argumentName => $getter) {
            if (!\is_string($argumentName) || !\is_string($getter)) {
                return null;
            }

            $getters[$argumentName] = $getter;
        }

        return $getters === [] ? null : ['order' => array_keys($getters), 'getters' => $getters];
    }
