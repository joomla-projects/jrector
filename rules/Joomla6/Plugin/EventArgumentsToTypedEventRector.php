    /**
     * The effective map, i.e. the default map merged with the configured one.
     *
     * @var array<string, array{order: string[], getters: array<string, string>}>
     */
    private array $eventArgumentMap = self::DEFAULT_EVENT_ARGUMENT_MAP;

    public function __construct(
        private readonly ReflectionProvider $reflectionProvider,
    ) {
    }

    /**
     * @param array<string, mixed> $configuration
     */
    public function configure(array $configuration): void
    {
        $configuredMap = $configuration[self::EVENT_ARGUMENT_MAP] ?? [];

        if (!\is_array($configuredMap)) {
            return;
        }

        $normalised = [];

        foreach ($configuredMap as $className => $definition) {
            if (!\is_string($className) || !\is_array($definition)) {
                continue;
            }

            $normalisedDefinition = $this->normaliseDefinition($definition);

            if ($normalisedDefinition !== null) {
                $normalised[ltrim($className, '\\')] = $normalisedDefinition;
            }
        }

        // Configured entries override the generated defaults.
        $this->eventArgumentMap = $normalised + self::DEFAULT_EVENT_ARGUMENT_MAP;
    }

